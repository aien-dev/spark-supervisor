#!/bin/sh
# gen-syscalls.sh: regenerate om/syscalls.om, the Linux ARM64 syscall numbers of the systemd syscall
# groups that service files name (syscalls @system-service @mount @ns, syscalls-deny @privileged
# @resources). This is a data generator, not part of the supervisor: the oracles are the host's
# `systemd-analyze syscall-filter` (group membership) and the kernel headers through `cpp`
# (<asm/unistd.h>, ARM64 numbers). tests/run.sh runs it with --check and fails on any difference.
#   tools/gen-syscalls.sh           rewrite om/syscalls.om
#   tools/gen-syscalls.sh --check   compare only (exit 1 on a difference)
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
out=$here/om/syscalls.om
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

[ "$(uname -m)" = aarch64 ] || { echo "gen-syscalls: ARM64 host required" >&2; exit 2; }

# Kernel table: name -> number, aliases (__NR3264_*) resolved by the preprocessor.
{ echo '#include <asm/unistd.h>'
  echo '#include <asm/unistd.h>' | cpp -dM |
    awk '$1=="#define" && $2 ~ /^__NR_/ {n=$2; sub(/^__NR_/,"",n); print "SYS " n " __NR_" n}'
} | cpp -P | awk '$1=="SYS" && $3 ~ /^[0-9]+$/ {print $2, $3}' |
  grep -v -E '^(syscalls|arch_specific_syscall) ' | sort -u > "$tmp/all"

SYSTEMD_COLORS=0 systemd-analyze syscall-filter --no-pager 2>/dev/null | sed 's/\x1b\[[0-9;]*m//g' > "$tmp/groups"
members() { awk -v G="$1" '/^@/ {g=$1; next} /^[[:space:]]*#/ || /^[[:space:]]*$/ {next} g==G {gsub(/[[:space:]]/,""); print}' "$tmp/groups"; }
expand() {
  todo="$*"; seen=""; : > "$tmp/acc"
  while [ -n "$todo" ]; do
    set -- $todo; x=$1; shift; todo="$*"
    case " $seen " in *" $x "*) continue ;; esac
    seen="$seen $x"
    for w in $(members "$x"); do case $w in @*) todo="$todo $w" ;; *) echo "$w" >> "$tmp/acc" ;; esac; done
  done
  sort -u "$tmp/acc"
}
numbers() { awk 'NR==FNR {a[$1]=1; next} ($1 in a) {print $2}' "$1" "$tmp/all" | sort -n | paste -sd ' ' -; }

expand @system-service > "$tmp/ss"
expand @mount > "$tmp/mount"
expand @privileged > "$tmp/priv"
expand @resources > "$tmp/res"
printf 'unshare\nsetns\n' > "$tmp/ns"
[ -s "$tmp/ss" ] && [ "$(wc -l < "$tmp/ss")" -gt 300 ] || { echo "gen-syscalls: @system-service expansion looks wrong" >&2; exit 2; }

{
  echo "note GENERATED by tools/gen-syscalls.sh from systemd-analyze syscall-filter ($(systemd-analyze --version | head -1 | awk '{print $2}'))"
  echo "note and <asm/unistd.h> (ARM64). Do not edit; rerun the generator. Numbers allowed per group."
  echo "text sysss \"$(numbers "$tmp/ss")\""
  echo "text sysmnt \"$(numbers "$tmp/mount")\""
  echo "text sysns \"$(numbers "$tmp/ns")\""
  echo "text syspriv \"$(numbers "$tmp/priv")\""
  echo "text sysres \"$(numbers "$tmp/res")\""
} > "$tmp/out"

if [ "${1:-}" = --check ]; then
  if cmp -s "$tmp/out" "$out"; then echo "SYSCALLS-TABLE PASS"; exit 0; fi
  echo "SYSCALLS-TABLE FAIL: om/syscalls.om differs from the host oracle" >&2
  diff "$out" "$tmp/out" >&2 || true
  exit 1
fi
cp "$tmp/out" "$out"
echo "wrote $out"
